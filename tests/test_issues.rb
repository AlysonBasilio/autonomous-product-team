class TestIssuesAppendHistory < Minitest::Test
  include DBHelper

  def setup
    setup_in_memory_db
    @issue = Issue.create!(input_text: 'Fix it', repo_url: 'https://github.com/a/b',
                           lifecycle_stage: 'coding')
  end

  def teardown
    teardown_in_memory_db
  end

  def test_appends_entry
    Issues.append_history(@issue.id, { 'task' => 'code.md', 'duration_s' => 60 })
    @issue.reload
    assert_equal 1, @issue.history.length
    assert_equal 'code.md', @issue.history.first['task']
  end

  def test_appends_multiple_entries_in_order
    Issues.append_history(@issue.id, { 'task' => 'code.md' })
    Issues.append_history(@issue.id, { 'task' => 'test.md' })
    @issue.reload
    assert_equal 2, @issue.history.length
    assert_equal 'code.md', @issue.history[0]['task']
    assert_equal 'test.md', @issue.history[1]['task']
  end

  def test_returns_nil_for_unknown_id
    assert_nil Issues.append_history('nonexistent-uuid', { 'task' => 'code.md' })
  end
end
